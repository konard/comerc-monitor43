// Package mute предоставляет бизнес-логику заглушения алертов.
//
// Заглушение (mute) позволяет временно или навсегда отключить уведомления
// для конкретного монитора. Поддерживаются пользовательский и глобальный scope.
//
// Основные компоненты:
//   - MuteService: Сервис управления заглушениями алертов
//
// Использование:
//
//	muteService := mute.NewMuteService(
//	    muteRepo,
//	    auditService,
//	    tracer,
//	    metrics,
//	)
//	err := muteService.MuteForUser(ctx, userID, monitorID, &mutedUntil)
//	isMuted, err := muteService.IsMuted(ctx, userID.String(), monitorID.String())
//
// Ключевые особенности:
//   - Пользовательские заглушения: влияние только на конкретного пользователя
//   - Глобальные заглушения: влияние на всех пользователей монитора
//   - Поддержка indefinite (бессрочных) заглушений
//   - Автоматическая проверка активных заглушений с учётом muted_until
//   - Запись действий в журнал аудита
//   - OpenTelemetry трейсинг для всех операций
package mute
