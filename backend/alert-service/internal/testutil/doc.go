// Package testutil предоставляет утилиты для тестирования alert-service.
//
// Основные компоненты:
//   - SetupPostgres: Создание тестовой PostgreSQL базы данных
//   - TeardownPostgres: Удаление тестовой базы данных
//   - Test helpers: Вспомогательные функции для создания тестовых данных
//
// Использование:
//
//	db := SetupPostgres(t)
//	defer TeardownPostgres(t, db)
//
// Ключевые особенности:
//   - Использование testcontainers для создания временных контейнеров
//   - Ожидание готовности сервиса перед выполнением тестов
//   - Корректная очистка ресурсов после завершения тестов
//   - Поддержка флага -short для пропуска integration тестов
//
// Контекст DOD:
//   - Соответствует требованию DOD 3.2 Integration Tests
//   - Автоматический запуск и остановка контейнеров
//   - Поддержка флага -short: `t.Skip("integration test")`
//   - Proper cleanup ресурсов после завершения тестов
